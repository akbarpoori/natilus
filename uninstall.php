<?php
/**
 * Uninstall cleanup for Natilus.
 * Removes tables, options (including the encrypted provider chain), crons,
 * post meta, transients, the activation fatal log and capabilities.
 *
 * @package ai-content-publishing-agent
 * @license GPL-2.0-or-later
 */

if ( ! defined( 'WP_UNINSTALL_PLUGIN' ) ) {
        exit;
}

global $wpdb;

// Drop custom tables (kic_bulk_queue is the v1.x generation queue, kept here
// so legacy installs get cleaned too).
$wpdb->query( "DROP TABLE IF EXISTS {$wpdb->prefix}kic_usage" ); // phpcs:ignore WordPress.DB
$wpdb->query( "DROP TABLE IF EXISTS {$wpdb->prefix}kic_bulk_queue" ); // phpcs:ignore WordPress.DB

/*
 * Options. kic_provider_chain holds ENCRYPTED API keys and MUST be removed;
 * the rest are settings, diagnostics and one-time flags.
 */
foreach ( array(
        'kic_settings',
        'kic_provider_chain',   // encrypted provider keys.
        'kic_chain_events',     // durable failover log.
        'kic_prompt_library',   // v1.x prompt library.
        'kic_prompt_skills',    // v1.x prompt skills.
        'kic_wizard_done',
        'kic_spike_notice',
        'kic_spike_last_mail',
        'kic_activation_fatal',
        'kic_activation_notice',
) as $kic_option ) {
        delete_option( $kic_option );
}

// Scheduled cron events (recurring reports + per-post drip publishes).
wp_clear_scheduled_hook( 'kic_weekly_summary' );
wp_clear_scheduled_hook( 'kic_daily_usage_check' );

/*
 * Per-post drip cron events carry a post id argument; sweep the cron array
 * directly so every single event is removed (a full cron rebuild is too
 * destructive — we remove only our own entries).
 */
$kic_crons = (array) _get_cron_array();
foreach ( $kic_crons as $kic_time => $kic_hooks ) {
        if ( ! is_array( $kic_hooks ) || ! isset( $kic_hooks['kic_drip_publish'] ) ) {
                continue;
        }
        foreach ( $kic_hooks['kic_drip_publish'] as $kic_sig => $kic_event ) {
                if ( is_array( $kic_event ) ) {
                        wp_unschedule_event( (int) $kic_time, 'kic_drip_publish', isset( $kic_event['args'] ) ? $kic_event['args'] : array() );
                }
        }
}

// Post meta generated by the plugin.
$wpdb->query( "DELETE FROM {$wpdb->postmeta} WHERE meta_key LIKE '\_kic\_%'" ); // phpcs:ignore WordPress.DB

// Per-user prompt history.
$wpdb->query( "DELETE FROM {$wpdb->usermeta} WHERE meta_key LIKE 'kic\_prompt\_history%'" ); // phpcs:ignore WordPress.DB

// Transients (rate limiting, stats cache, models cache, provider health).
$wpdb->query( "DELETE FROM {$wpdb->options} WHERE option_name LIKE '\_transient\_kic\_%' OR option_name LIKE '\_transient\_timeout\_kic\_%' OR option_name LIKE '\_transient\_kic\_ph\_%' OR option_name LIKE '\_transient\_timeout\_kic\_ph\_%' OR option_name LIKE '\_transient\_kic\_models\_%' OR option_name LIKE '\_transient\_timeout\_kic\_models\_%'" ); // phpcs:ignore WordPress.DB

// Activation fatal log in uploads (best-effort).
$kic_upload = wp_upload_dir();
if ( is_array( $kic_upload ) && ! empty( $kic_upload['basedir'] ) ) {
        $kic_fatal_log = trailingslashit( $kic_upload['basedir'] ) . 'kic-activation-error.log';
        if ( is_readable( $kic_fatal_log ) ) {
                wp_delete_file( $kic_fatal_log ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_delete_file -- wp_delete_file on purpose.
        }
}

// Capabilities.
foreach ( array( 'administrator', 'editor' ) as $kic_role_name ) {
        $kic_role = get_role( $kic_role_name );
        if ( $kic_role ) {
                $kic_role->remove_cap( 'kubit_ai_compose' );
        }
}
